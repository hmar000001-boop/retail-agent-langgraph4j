package com.example.retail.agent;

import static org.bsc.langgraph4j.StateGraph.END;
import static org.bsc.langgraph4j.StateGraph.START;
import static org.bsc.langgraph4j.action.AsyncEdgeAction.edge_async;
import static org.bsc.langgraph4j.action.AsyncNodeAction.node_async;

import java.util.HashMap;
import java.util.Map;
import java.util.Objects;
import java.util.UUID;
import org.bsc.langgraph4j.CompiledGraph;
import org.bsc.langgraph4j.CompileConfig;
import org.bsc.langgraph4j.GraphInput;
import org.bsc.langgraph4j.GraphStateException;
import org.bsc.langgraph4j.RunnableConfig;
import org.bsc.langgraph4j.StateGraph;
import org.bsc.langgraph4j.checkpoint.BaseCheckpointSaver;

/**
 * Owns the primary LangGraph4j topology and thread/checkpoint lifecycle.
 * Application node behavior lives in {@link RetailGraphNodes}; this class contains orchestration only.
 */
public final class RetailAgentGraph {
    private final RetailGraphNodes nodes;
    private final AgentSettings settings;
    private final BaseCheckpointSaver checkpointSaver;
    private final CompiledGraph<RetailState> graph;
    /** Fixed lock stripes serialize same-thread lifecycle operations without an unbounded lock-map leak.
     * Cross-instance coordination is delegated to the durable store/API layer in the production hardening phase.
     */
    private final Object[] threadLocks = createLocks(256);

    public RetailAgentGraph(RetailGraphNodes nodes, AgentSettings settings, BaseCheckpointSaver checkpointSaver) {
        this.nodes = Objects.requireNonNull(nodes, "nodes");
        this.settings = Objects.requireNonNull(settings, "settings");
        this.checkpointSaver = Objects.requireNonNull(checkpointSaver, "checkpointSaver");
        this.graph = compileGraph();
    }

    public AgentResult ask(String customerId, String query) {
        return start(UUID.randomUUID().toString(), customerId, query);
    }

    /** Starts a new graph thread. Thread IDs are generated by the facade unless a caller supplies one explicitly. */
    public AgentResult start(String threadId, String customerId, String query) {
        requireText(threadId, "threadId");
        requireText(customerId, "customerId");
        requireText(query, "query");
        synchronized (threadLock(threadId)) {
            RunnableConfig runConfig = config(threadId);
            if (checkpointSaver.get(runConfig).isPresent()) {
                throw new IllegalStateException("A checkpoint already exists for thread " + threadId + "; use resume or a new thread id");
            }
            Map<String, Object> input = new HashMap<>();
            input.put(RetailState.THREAD_ID, threadId);
            input.put(RetailState.QUERY, query);
            input.put(RetailState.CUSTOMER, customerId);
            input.put(RetailState.ITERATION, 0);
            input.put(RetailState.PLANNING_ROUND, 0);
            input.put(RetailState.FAILURES, 0);
            input.put(RetailState.INTENTION, com.example.retail.core.IntentionRecord.start(query));
            input.put(RetailState.BUDGET, com.example.retail.core.ResourceBudget.start(settings.maxPlanningRounds(),
                    settings.maxToolCalls(), settings.maxModelCalls()));
            input.put(RetailState.UNCERTAINTY,
                    com.example.retail.core.UncertaintyEstimate.unknown("no proposal has been evaluated yet"));
            input.put(RetailState.APPROVAL_DECISION, "");
            input.put(RetailState.APPROVAL_ACTOR, "");
            input.put(RetailState.APPROVAL_DECISION_ID, "");
            return invoke(input, runConfig);
        }
    }

    /**
     * Resumes only an interrupted approval thread. LangGraph4j applies this update to the checkpoint
     * and continues at the node that was interrupted before execution.
     */
    public AgentResult resumeApproval(String threadId, String authenticatedSubjectId, String approvalId, boolean approved) {
        requireText(threadId, "threadId");
        requireText(authenticatedSubjectId, "authenticatedSubjectId");
        requireText(approvalId, "approvalId");
        synchronized (threadLock(threadId)) {
            RunnableConfig runConfig = config(threadId);
            var checkpoint = checkpointSaver.get(runConfig)
                    .orElseThrow(() -> new IllegalStateException("No checkpoint exists for thread " + threadId));
            Map<String, Object> saved = checkpoint.getState();
            String owner = Objects.toString(saved.get(RetailState.CUSTOMER), "");
            String status = Objects.toString(saved.get(RetailState.APPROVAL_STATUS), "NOT_REQUIRED");
            boolean required = Boolean.TRUE.equals(saved.get(RetailState.APPROVAL_REQUIRED));
            if (!owner.equals(authenticatedSubjectId)) {
                throw new SecurityException("The authenticated subject does not own this graph thread");
            }
            if (!required || !"PENDING".equals(status)) {
                throw new IllegalStateException("Thread is not waiting for an approval decision");
            }
            Object storedRequest = saved.get(RetailState.APPROVAL_REQUEST);
            if (!(storedRequest instanceof com.example.retail.agent.domain.PendingActionApproval request)) {
                throw new IllegalStateException("Pending approval request is missing from the checkpoint");
            }
            if (!request.approvalId().equals(approvalId)) {
                throw new SecurityException("Approval ID does not match the currently pending request");
            }
            Map<String, Object> approval = Map.of(
                    RetailState.APPROVAL_DECISION, approved ? "APPROVED" : "DENIED",
                    RetailState.APPROVAL_ACTOR, authenticatedSubjectId,
                    RetailState.APPROVAL_DECISION_ID, approvalId);
            try {
                // Supported LangGraph4j sequence: write the human decision into the saved state,
                // then resume from the checkpoint's recorded next node.
                RunnableConfig updated = graph.updateState(runConfig, approval, null);
                RetailState current = graph.invoke(GraphInput.resume(), updated)
                        .orElseThrow(() -> new IllegalStateException("approval resume returned no state"));
                return result(threadId, current);
            } catch (SecurityException | IllegalStateException e) {
                throw e;
            } catch (Exception e) {
                throw new IllegalStateException("Unable to update and resume approval thread " + threadId, e);
            }
        }
    }

    public String graphDiagram() {
        return graph.getGraph(org.bsc.langgraph4j.GraphRepresentation.Type.MERMAID,
                "Retail agent — primary LangGraph4j runtime", true).getContent();
    }

    private AgentResult invoke(Map<String, Object> input, RunnableConfig config) {
        RetailState end = graph.invoke(GraphInput.args(input), config)
                .orElseThrow(() -> new IllegalStateException("graph returned no state"));
        return result(config.threadId().orElseThrow(), end);
    }

    private static AgentResult result(String threadId, RetailState state) {
        com.example.retail.agent.domain.PendingActionApproval pending = state.pendingApproval()
                ? state.approvalRequest().orElseThrow() : null;
        return new AgentResult(state.answer(), !state.clarification().isBlank(), state.iteration(), state.failures(),
                state.trace(), state.observations(), threadId, pending != null, state.approvalStatus(), pending);
    }

    private RunnableConfig config(String threadId) {
        return RunnableConfig.builder().threadId(threadId)
                .putMetadata("runtime", "retail-agent-langgraph4j")
                .putMetadata("runtimeVersion", "phase-2")
                .build();
    }

    private CompiledGraph<RetailState> compileGraph() {
        try {
            StateGraph<RetailState> planning = new StateGraph<>(RetailState.SCHEMA, RetailState::new)
                    .addNode("propose", nodes::proposeAsync)
                    .addNode("evaluate", node_async(nodes::evaluate))
                    .addNode("select", node_async(nodes::select))
                    .addEdge(START, "propose")
                    .addEdge("propose", "evaluate")
                    .addEdge("evaluate", "select")
                    .addEdge("select", END);

            StateGraph<RetailState> root = new StateGraph<>(RetailState.SCHEMA, RetailState::new)
                    .addNode("begin_retrieval", node_async(nodes::beginRetrieval))
                    .addNode("retrieve_episodic", node_async(nodes::retrieveEpisodic))
                    .addNode("retrieve_semantic", node_async(nodes::retrieveSemantic))
                    .addNode("retrieve_procedural", node_async(nodes::retrieveProcedural))
                    .addNode("retrieve_catalog", node_async(nodes::retrieveCatalog))
                    .addNode("admit_workspace", node_async(nodes::admitWorkspace))
                    .addNode("planning", planning)
                    .addNode("authorize", node_async(nodes::authorize))
                    .addNode("execute", node_async(nodes::execute))
                    .addNode("execute_approved", node_async(nodes::executeApproved))
                    // Tool output must win fresh workspace admission before reflection; reflection
                    // must not read stale pre-execution context or bypass the B3 budget.
                    .addNode("refresh_workspace", node_async(nodes::admitWorkspace))
                    .addNode("reflect", nodes::reflectAsync)
                    .addNode("recover", node_async(nodes::recover))
                    .addNode("learn", node_async(nodes::learn))
                    .addNode("answer", nodes::answerAsync);

            // The four retrieval branches are a single parallel fan-out/fan-in step. Their writes
            // target distinct state keys; only audit trace uses an append reducer.
            root.addEdge(START, "begin_retrieval");
            root.addEdge("begin_retrieval", "retrieve_episodic");
            root.addEdge("begin_retrieval", "retrieve_semantic");
            root.addEdge("begin_retrieval", "retrieve_procedural");
            root.addEdge("begin_retrieval", "retrieve_catalog");
            root.addEdge("retrieve_episodic", "admit_workspace");
            root.addEdge("retrieve_semantic", "admit_workspace");
            root.addEdge("retrieve_procedural", "admit_workspace");
            root.addEdge("retrieve_catalog", "admit_workspace");
            root.addEdge("admit_workspace", "planning");

            root.addConditionalEdges("planning", edge_async(RetailState::route), Map.of(
                    "authorize", "authorize", "replan", "begin_retrieval", "clarify", "learn",
                    "finish", "learn", "abort", "learn"));
            root.addConditionalEdges("authorize", edge_async(RetailState::route), Map.of(
                    "execute", "execute", "approval", "execute_approved"));
            root.addConditionalEdges("execute", edge_async(RetailState::route), Map.of(
                    "observe", "refresh_workspace", "finish", "learn"));
            root.addConditionalEdges("execute_approved", edge_async(RetailState::route), Map.of(
                    "observe", "refresh_workspace", "finish", "learn"));
            root.addEdge("refresh_workspace", "reflect");
            root.addConditionalEdges("reflect", edge_async(RetailState::route), Map.of(
                    "continue", "begin_retrieval", "recover", "recover", "finish", "learn"));
            root.addConditionalEdges("recover", edge_async(RetailState::route), Map.of(
                    "continue", "begin_retrieval", "finish", "learn"));
            root.addEdge("learn", "answer");
            root.addEdge("answer", END);

            long applicationBound = 8L * (settings.maxIterations() + settings.maxPlanningRounds()) + 16L;
            int recursionLimit = (int) Math.max(64L, applicationBound);
            CompileConfig compileConfig = CompileConfig.builder()
                    .checkpointSaver(checkpointSaver)
                    .releaseThread(false)
                    .interruptBefore("execute_approved")
                    .recursionLimit(recursionLimit)
                    .graphId("retail-agent-primary")
                    .build();
            return root.compile(compileConfig);
        } catch (GraphStateException e) {
            throw new IllegalStateException("invalid primary LangGraph4j graph", e);
        }
    }

    private Object threadLock(String threadId) {
        return threadLocks[Math.floorMod(threadId.hashCode(), threadLocks.length)];
    }

    private static Object[] createLocks(int count) {
        Object[] locks = new Object[count];
        java.util.Arrays.setAll(locks, ignored -> new Object());
        return locks;
    }

    private static void requireText(String value, String name) {
        if (value == null || value.isBlank()) throw new IllegalArgumentException(name + " must not be blank");
    }
}
